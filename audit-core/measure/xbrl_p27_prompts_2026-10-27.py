"""封 docs/XBRL_P27_SAMPLE_SEAL_2026-10-27.md §3-3(書き手の指示文)と §5-6(読み手の指示文)の**字そのまま**の定数。

この file の字は封の字の写しで、1 字も変えない(封の門 tests/measure/test_xbrl_p27_sample_seal.py が、封の文書のコード塊と
1 字ずつ照らす。変えたら赤になる)。書き手の取りまとめと読み手の取りまとめの script は、ここから読む。通信しない・鍵に触れない。

書き手の指示文の `{型の文}` と `{companies の JSON}`・`{financials の JSON}`・`{ratios の JSON}` だけを埋める
(`render_writer_prompt`。1 回の走査で置き換えるので、埋め込んだ JSON の中の `{…}` の字が再び置き換わることはない)。
"""
import re

# 封 §3-3 のコード塊(字のとおり)
WRITER_TEMPLATE = """あなたは日本の上場会社の財務を読む担当です。下に、ある会社について外部の財務データベースの API が返した JSON が 3 つあります(会社の情報・数期分の財務の数・財務の比率)。この JSON だけを材料に、日本語の財務分析レポートを 1 本書いてください。

決まり:
1. 材料は下の JSON だけです。ほかの資料・記憶・ウェブは使わないでください。file を読む・検索する・通信するなどの道具も使わないでください。
2. 対象は JSON の中で最も新しい決算期です。前の期との比較を入れてかまいません。
3. 数は JSON の値から書いてください。読み手に分かりやすい単位に直し、丸め方は自分で決めてかまいません。増減率や比率など JSON に無い数は、JSON の値から自分で計算してかまいません。
4. JSON から読めない事実(会社の方針・見通し・外部の出来事など)は書かないでください。値が null の項目は書かないでください。数から読める範囲の説明は書いてかまいません。
5. 形は次の型で書いてください: {型の文}
6. 1 行目に題を書き、その後に本文を書いてください。出力はレポートだけにしてください(前置き・注記・材料の説明・計算の過程は書かない)。

会社の情報(companies):
{companies の JSON}

財務の数(financials):
{financials の JSON}

財務の比率(ratios):
{ratios の JSON}"""

# 封 §3-3 の型の文(A・B・C)
TYPE_SENTENCES = {
    "A": "見出しつきの段落。見出しを 3〜5 個立て、それぞれの下に 2〜4 文の段落を書く。全体で 800〜1,200 字。",
    "B": "箇条書き。見出しは立てず、「・」で始まる箇条を 10〜20 個書く。1 つの箇条は 1〜2 文。全体で 600〜1,000 字。",
    "C": "短い要約。見出しも箇条も使わず、1〜2 段落で書く。全体で 300〜500 字。",
}

# 封 §5-6 のコード塊(字のとおり)
READER_PROMPT = """あなたは、ある文の数を有価証券報告書の XBRL に当てた道具の判定を 1 行ずつ読む担当です。文は、外部の財務データベースの値だけを材料に AI が書いた財務レポートです。道具の判定が正しいかではなく、食い違いがどちらの側から来たかを読んでください。

1 行ごとに、次の札を 1 つずつ付けてください。
- 側: 文 / 道具 / 分からない
  - 文: 文の数か書き方の側に食い違いの元がある。
  - 道具: 文は材料に照らして正しく、道具が別の数・別の期・別の向きと比べた。
  - 分からない: 渡された材料では決められない。
- 側が「文」なら細目: 文1(文の数がデータベースの値と違う)/ 文2(文の数はデータベースの値どおりだが、XBRL の fact と違う)/ 文3(丸めの差。1 単位の差)/ 文4(データベースの別の項目・別の期の数を書いた)
- 側が「道具」なら細目: 道1(括弧内や「前期の」の数を当期に当てた)/ 道2(増減の語が要因の項目にかかるのに、主語の向きと比べた)/ 道3(率の取り方。減少率・増加率・前期比)/ 道4(別の要素・1 株当たり・別の区分に当てた)/ 道5(その他。形を 10〜40 字で書く)
- 理由: 1〜2 文。

決まり: 渡した材料(文の段落・判定の欄・データベースの応答・XBRL の fact)だけで読んでください。どちらとも決められないときは「分からない」にしてください。ほかの読み手の札は見ないでください。"""

PLACEHOLDERS = ("{型の文}", "{companies の JSON}", "{financials の JSON}", "{ratios の JSON}")
_PLACEHOLDER_RE = re.compile("|".join(re.escape(p) for p in PLACEHOLDERS))


def render_writer_prompt(style, companies_json, financials_json, ratios_json):
    """書き手に渡す指示文の全体。style は "A"・"B"・"C"。JSON は応答の字そのまま(整形し直さない)。"""
    values = {
        "{型の文}": TYPE_SENTENCES[style],
        "{companies の JSON}": companies_json,
        "{financials の JSON}": financials_json,
        "{ratios の JSON}": ratios_json,
    }
    return _PLACEHOLDER_RE.sub(lambda m: values[m.group(0)], WRITER_TEMPLATE)
